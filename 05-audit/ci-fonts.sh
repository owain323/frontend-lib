#!/usr/bin/env bash
# ============================================================================
# ci-fonts.sh — 给 CI 装一套**确定**的字体
# ============================================================================
# 为什么需要
# ---------------------------------------------------------------------------
# 本库不含任何 `@font-face`：字体走系统栈（`Segoe UI` / `Microsoft YaHei` /
# `Noto Sans CJK SC` …）。ubuntu runner 默认只有极少数拉丁字体，
# CJK 与阿拉伯/希伯来文会**整段变成方框** —— 那样截出来的基线图
# 看起来"有图"，实际什么文字都没渲染。基线一旦这么录，
# 以后真回归（字被裁、行高塌了）也看不出来，因为基线里本来就没有字。
#
# ⇒ 所以在录 Linux 基线**和**跑 Linux 视觉门禁之前，都要先装同一批字体。
#   两个工作流调用的是**这一个脚本**，不是各自抄一份 apt 命令 ——
#   两份包名清单迟早会分叉，而分叉的后果是"基线用 A 字体录、门禁用 B 字体判"。
#
# ⚠️ 诚实的边界：apt 包里字体的**版本**会随时间变。
#    某天 CI 视觉门禁红了、本机却没事，先查是不是 runner 的字体升级了；
#    确认是字体变化就重录 `_baseline-linux*`。这不是 bug，是"基线锚在渲染环境上"
#    这件事的固有代价；把它写在这里，比让你猜要好。
# ============================================================================
set -euo pipefail

sudo apt-get update -qq
sudo apt-get install -y -qq --no-install-recommends \
  fonts-noto-cjk \
  fonts-noto-core

echo "已装字体：$(fc-list 2>/dev/null | wc -l) 条"
# 点名验一遍：CJK / 阿拉伯 / 希伯来 三类各要有至少一条，
# 否则"装好了"只是 apt 说装好了（这类假绿我们已经踩过）。
for probe in "CJK" "Arabic" "Hebrew"; do
  n=$(fc-list 2>/dev/null | grep -ci "$probe" || true)
  echo "  $probe: $n 条"
  if [ "${n:-0}" -lt 1 ]; then
    echo "::error::字体缺失：$probe 一条都没有 —— 视觉基线会录成方框，拒绝继续"
    exit 1
  fi
done
