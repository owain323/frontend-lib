/**
 * emit.js — 「统一事件发射」工具核
 *
 * ==========================================================================
 * 🔴 为什么要抽成核（不是因为懒，是因为这里有一处**必须只有一份**的兜底）
 * --------------------------------------------------------------------------
 *   老 WebView（以及部分精简档内核）**没有 `CustomEvent` 构造函数**，
 *   只有 `document.createEvent('CustomEvent')` + `initCustomEvent()`。
 *
 *   ⚠️ 这个坑的恶劣之处：
 *     · `new CustomEvent(...)` 在老环境里**抛异常**，而且是在**用户交互的路径上**抛
 *       （点一下按钮才炸），本地 Chrome 永远测不出来；
 *     · 若每个组件各写一次兜底，8 个组件里迟早有一个只写了新写法
 *       ⇒ 那个组件在真机上"点了没反应"，而且控制台不一定有线索。
 *
 *   ⇒ 兜底逻辑只能有一份，由门禁保证每个使用点逐行一致。
 *
 * ==========================================================================
 * 事件模型（统一约定，不是各组件各起各的）
 * --------------------------------------------------------------------------
 *   ① 事件名一律 `fl-` 前缀。
 *      为什么：组件内部有原生 `<input>` / `<button>`，它们的 `change` / `click`
 *      会**冒泡上来**；不加前缀 ⇒ 调用方 `el.addEventListener('change', ...)`
 *      会收到自己没订阅过的东西。
 *   ② 一律 `bubbles: true`：调用方可以在**祖先**上做事件委托。
 *   ③ 一律 `cancelable: false`：本库的事件是**通知**，不是"可撤销的动作"。
 *      （真要拦就用回调里 return false，别把两件事混在事件上。）
 *   ④ 一律在**组件根元素**上派发，不在内部子元素上。
 *   ⑤ `detail` 统一带 `value`（有值的组件），组件自己的字段另加。
 *   ⑥ 委托时**必须认 `e.target`**：事件会冒泡，嵌套组件（如 tabs 里放
 *      select）会在同一个祖先上收到两个 `fl-change`；靠 `e.target` 认
 *      组件根，事件名不能代替身份。
 *   ⑦ 顺序：**先派发事件，再调回调**。回调是调用方写的，可能抛异常；
 *      事件先落地 ⇒ 回调炸了也不会连累挂在祖先上的其它订阅者。

 * ==========================================================================
 * 用法
 * --------------------------------------------------------------------------
 *   flEmit(root, 'fl-change', { value: v });
 *   // 名字里已带 fl- 就不重复加；不带就自动补 —— 防止漏写前缀
 *
 * ⚠️ 它**不是"行为核"**（不像 Esc 关闭那样是用户能感知的行为），
 *   所以不进 `ai/behaviors.json` 的行为矩阵；它是**工具核**。
 *
 * ==========================================================================
 * ⚠️ 注入块里的注释会**被复制进每个使用点**（gzip 也要算）
 * --------------------------------------------------------------------------
 *   ⇒ 长解释一律写在**本文件头**（BEGIN 标记之外），注入块内只留一行提示。
 *
 * ==========================================================================
 * 约束：ES5 · 零依赖 · 可被整块注入 · 不新增任何全局
 * ==========================================================================
 */
/* ==== BEHAVIOR CORE BEGIN: emit ==== */
var flEmit = function (el, name, detail) {
  if (!el || !el.dispatchEvent) return null;
  var type = name.indexOf('fl-') === 0 ? name : 'fl-' + name;
  var ev = null;
  /* 老 WebView 没有 CustomEvent 构造函数 ⇒ 兜底走 createEvent（理由见文件头）*/
  if (typeof window.CustomEvent === 'function') {
    try {
      ev = new window.CustomEvent(type, {
        detail: detail || null, bubbles: true, cancelable: false
      });
    } catch (e) { ev = null; }
  }
  if (!ev) {
    try {
      ev = document.createEvent('CustomEvent');
      ev.initCustomEvent(type, true, false, detail || null);
    } catch (e2) { return null; }
  }
  el.dispatchEvent(ev);
  return ev;
};
/* ==== BEHAVIOR CORE END: emit ==== */
