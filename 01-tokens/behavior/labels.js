/**
 * labels.js — 「文案覆盖合并」工具核
 *
 * ==========================================================================
 * 🔴 为什么要有这个核
 * --------------------------------------------------------------------------
 *   0.26.0 给组件加 `labels`（读屏 / 可见文案覆盖）时，最初的写法是
 *   在 9 个组件里各贴一份合并函数：
 *
 *       for (k in defaults) { out[k] = src[k] == null ? defaults[k] : src[k]; }
 *
 *   九份一模一样的循环，只差 `defaults` 的字面量。这与 I-14 是同一条病：
 *   **同一份逻辑写 N 份**。后果不是"难看"，是**修正只到一处**：
 *     · 以后要支持"传 null 表示删掉这条文案"→ 改 1 处、漏 8 处；
 *     · 要支持嵌套命名空间 → 同上；
 *     · 某处写成 `src[k] || defaults[k]`，空字符串就再也覆盖不掉 ——
 *       而这种偏差在 9 份副本里肉眼几乎看不出来。
 *
 *   ⇒ 真值源一份（本文件），生成进使用点，`gen-behavior --check` 证明跟随。
 *      使用点仍然**各自保留自己的 `defaults` 字面量** —— 那是组件的事实，
 *      不是可以共享的代码。
 *
 * ==========================================================================
 * 语义（三句话，必须与实现逐字对应）
 * --------------------------------------------------------------------------
 *   ① `undefined` / `null` ⇒ 用默认值（"没传"和"显式取消"等价）；
 *   ② 其他任何值（含 `''`、`0`、`false`）⇒ **原样采用** ——
 *      用 `||` 判断会把空字符串吞掉，那是错误的；
 *   ③ 只认 `defaults` 里有的键 —— 拼错的键不会悄悄生效（避免"传了却没反应"）。
 * ==========================================================================
 */
/* ==== BEHAVIOR CORE BEGIN: labels ==== */
var flLabels = function (defaults, src) {
  src = src || {};
  var out = {};
  var k;
  for (k in defaults) {
    if (Object.prototype.hasOwnProperty.call(defaults, k)) {
      out[k] = (src[k] === undefined || src[k] === null) ? defaults[k] : src[k];
    }
  }
  return out;
};
/* ==== BEHAVIOR CORE END: labels ==== */
